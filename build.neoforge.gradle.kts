// The subproject is named "<mc>-neoforge", so Stonecutter's default property tag is that
// whole string and the ["1.21.1"] tables in stonecutter.properties.toml would not be
// flattened. Declaring the Minecraft version as a tag restores that.
//
// Only the version, never "neoforge": a tag is stripped from *any* segment of a property
// path, so a "neoforge" tag would turn `deps.neoforge` into `deps`. That is why the
// property tables are keyed by Minecraft version alone and the loader is encoded in the
// key name (deps.neoforge / deps.fabric_api) rather than in a [neoforge."1.21.1"] table.
stonecutter.properties.tags(stonecutter.current.version)

// ---------------------------------------------------------------------------
// Video playback
// ---------------------------------------------------------------------------
// FFmpeg is not bundled in the jar. The mod downloads the official ffmpeg (and
// ffprobe) build into the game folder on first launch — the same approach
// already used for yt-dlp — and shells out to the binaries (see MediaBinaries /
// FFmpegCli). This keeps the distributed jar small and avoids shipping native
// libraries for every platform.

// ---------------------------------------------------------------------------
// Properties
// ---------------------------------------------------------------------------
// Everything below comes from stonecutter.properties.toml. Version-specific
// tables are already flattened for the version this subproject builds, so
// `deps.neoforge` resolves to a different value in versions/1.21.1 and
// versions/1.21.4.
fun prop(name: String): String = project.property(name).toString()

val modId = prop("mod.id")
val modName = prop("mod.name")
val modLicense = prop("mod.license")
val modVersion = prop("mod.version")
val modGroup = prop("mod.group")
val apiVersion = prop("mod.api_version")
val loaderVersionRange = prop("mod.loader_version_range")

val minecraftVersion = prop("deps.minecraft")
val minecraftVersionRange = prop("deps.minecraft_range")
val neoVersion = prop("deps.neoforge")
val javaVersion = prop("deps.java")
// Empty for a Minecraft version Parchment has not published mappings for.
val parchmentVersion = prop("deps.parchment")

version = modVersion
group = modGroup

base {
    // Version- *and* loader-qualified: the same Minecraft version is built for both
    // loaders, so without the suffix the two jars would overwrite each other.
    archivesName = "$modId-$minecraftVersion-neoforge"
}

sourceSets.main {
    // The Fabric bridge imports Fabric API, which is not on this classpath. Whole files
    // that belong to one loader are separated by package and excluded here rather than
    // wrapped in a `//? if neoforge` guard: stonecutter.filters would not help, since it
    // only decides which files the preprocessor visits, not which ones javac compiles.
    java.exclude("**/platform/fabric/**")

    resources {
        // Include resources generated by data generators.
        srcDir("src/generated/resources")

        // Exclude common development only resources from finalized outputs
        exclude("**/*.bbmodel") // BlockBench project files
        exclude("src/generated/**/.cache") // datagen cache files
    }
}

