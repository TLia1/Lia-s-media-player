// Expands the declared properties in neoforge.mods.toml. A missing property
// results in an error. Properties are expanded using ${} Groovy notation.
tasks.withType<ProcessResources>().configureEach {
    val replaceProperties = mapOf(
        "minecraft_version" to minecraftVersion,
        "minecraft_version_range" to minecraftVersionRange,
        "neo_version" to neoVersion,
        "loader_version_range" to loaderVersionRange,
        "mod_id" to modId,
        "mod_name" to modName,
        "mod_license" to modLicense,
        "mod_version" to modVersion,
        "api_version" to apiVersion,
    )
    inputs.properties(replaceProperties)

    // Both metadata files live in the shared src/main/resources; each loader expands
    // and ships only its own.
    exclude("fabric.mod.json")

    filesMatching(listOf("META-INF/neoforge.mods.toml")) {
        expand(replaceProperties)
    }
}

// ---------------------------------------------------------------------------
// IntelliJ run configurations
// ---------------------------------------------------------------------------
// ModDevGradle names the module of the run configurations it generates by
// joining the Gradle project path with dots: ":1.21.1-neoforge" plus the "main"
// source set gives "Lia-s-media-player.1.21.1-neoforge.main". IntelliJ reserves
// '.' as the module-name separator and rewrites it to '_' inside each path
// segment, so the module it actually creates is
// "Lia-s-media-player.1_21_1-neoforge.main".
//
// Every Stonecutter subproject is named after a Minecraft version (plus its
// loader), so without the rewrite below every generated run configuration points
// at a module that does not exist. IntelliJ drops the reference silently and the configuration
// comes up as "module not specified", with the main class unresolvable and no
// classpath. MDG only sanitises spaces, not dots.
//
// This runs after MDG has populated the container, and is idempotent: a name
// whose segments hold no dots is left alone, so it stays correct if MDG ever
// fixes this upstream.
if (System.getProperty("idea.sync.active").toBoolean()) {
    val mdgModulePrefix = rootProject.name.replace(" ", "_") + project.path.replace(":", ".")
    val ideaModulePrefix = rootProject.name.replace(" ", "_").replace(".", "_") +
            project.path.split(":").filter { it.isNotEmpty() }
                    .joinToString("") { "." + it.replace(".", "_") }

    gradle.projectsEvaluated {
        val ideaProject = (rootProject.extensions.findByName("idea")
                as? org.gradle.plugins.ide.idea.model.IdeaModel)?.project
        val settings = (ideaProject as? ExtensionAware)
                ?.extensions?.findByType(org.jetbrains.gradle.ext.ProjectSettings::class.java)
        val runConfigurations = (settings as? ExtensionAware)
                ?.extensions?.findByName("runConfigurations")
                as? org.jetbrains.gradle.ext.RunConfigurationContainer
                ?: return@projectsEvaluated

        runConfigurations.withType(org.jetbrains.gradle.ext.ModuleRunConfiguration::class.java).all {
            val current = moduleName
            if (current != null && current.startsWith(mdgModulePrefix)) {
                moduleName = ideaModulePrefix + current.substring(mdgModulePrefix.length)
            }
        }
    }
}
