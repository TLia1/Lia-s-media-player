// ---------------------------------------------------------------------------
// ModDevGradle
// ---------------------------------------------------------------------------
// Captured outside the runs block: inside it, `project` resolves to the
// deprecated Dependencies.getProject().
val runsRoot = layout.projectDirectory.dir("run")

neoForge {
    version = neoVersion

    // Parchment stops at 1.21.11; 26.x builds against NeoForge's mappings alone.
    if (parchmentVersion.isNotEmpty()) {
        parchment {
            minecraftVersion = parchmentVersion.substringBefore(':')
            mappingsVersion = parchmentVersion.substringAfter(':')
        }
    }

    //accessTransformers.from("src/main/resources/META-INF/accesstransformer.cfg")

    // The jar declares two mods in neoforge.mods.toml (the mod itself and its
    // public API); both are produced by the main source set, so both have to be
    // mapped here or FML cannot locate the API mod in a dev run.
    mods {
        create(modId) {
            sourceSet(sourceSets.main.get())
        }
        create("liasmediaplayerapi") {
            sourceSet(sourceSets.main.get())
        }
    }

    runs {
        configureEach {
            // Recommended logging data for a userdev environment.
            // "SCAN": For mods scan.
            // "REGISTRIES": For firing of registry events.
            // "REGISTRYDUMP": For getting the contents of all registries.
            systemProperty("forge.logging.markers", "REGISTRIES")

            logLevel = org.slf4j.event.Level.DEBUG

            // Per-version game directories so worlds and configs of one target
            // never leak into another.
            gameDirectory = runsRoot.dir(name)
        }

        create("client") {
            client()
            // Comma-separated list of namespaces to load gametests from. Empty = all namespaces.
            systemProperty("neoforge.enabledGameTestNamespaces", modId)
        }

        create("server") {
            server()
            systemProperty("neoforge.enabledGameTestNamespaces", modId)
            programArgument("--nogui")
        }

        // Launches GameTestServer, runs all registered gametests, then exits.
        create("gameTestServer") {
            type = "gameTestServer"
            systemProperty("neoforge.enabledGameTestNamespaces", modId)
        }

        create("data") {
            // 1.21.4 split the datagen run type into clientData/serverData.
            if (stonecutter.eval(stonecutter.current.version, ">=1.21.4")) clientData() else data()

            programArguments.addAll(
                "--mod", modId,
                "--all",
                "--output", file("src/generated/resources/").absolutePath,
                "--existing", file("src/main/resources/").absolutePath,
            )
        }
    }
}

