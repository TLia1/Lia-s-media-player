package com.lia.mediaplayer.api.config;

/**
 * Defines the width of a config option in the config screen.
 */
public enum OptionWidth {
    /**
     * The option will take up the full width of the screen.
     */
    FULL,
    /**
     * The option will take up half the width of the screen, allowing two options to be placed side-by-side.
     */
    HALF
}
